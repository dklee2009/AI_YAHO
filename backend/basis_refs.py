NO_BASIS = "별도 법령·규정 조항 없음 (내부 IT 설계·운영 점검 항목)"

# (항목에서 찾을 단어, 근거 목록). 단어는 소문자로 비교한다. 위에서부터 순서대로 근거를 쌓는다.
