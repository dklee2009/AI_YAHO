# 전결 항목 확인 필요사항 속 약칭 → 정식 규정명
_APPROVAL_REF = re.compile(
    r"전결기준표\s*(공통\s*[①-⑳]|\d+-[가-힣])"
    r"|준칙\s*(제\d+조(?:\s*\d+호)?[①-⑳]?)"
    r"|금액산정\s*([①-⑳])"
)


def approval_basis(check: str) -> list[str]:
    refs = []
    for adm, con, amount in _APPROVAL_REF.findall(check):
        if adm:
            refs.append(f"{ADM} {adm}")
        elif con:
            refs.append(f"{CON} {con}")
        else:
            refs.append(f"{ADM} 금액산정 기준 {amount}")
    return refs


def item_basis(category_id: str, area: str, text: str, check: str, limit: int = 4) -> list[str]:
    """체크리스트 한 줄의 근거 규정 목록. 근거가 없으면 [NO_BASIS]."""
    refs = approval_basis(check) if category_id == "approval" else []
    if not refs:
        low = f"{area} {text} {check}".lower()
        for words, basis in BASIS_RULES:
            if any(w in low for w in words):
                refs += [b for b in basis if b not in refs]
    return refs[:limit] or [NO_BASIS]
