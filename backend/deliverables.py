# 규칙에 걸리지 않을 때 카테고리별 기본 단계
DEFAULT_PHASE = {"security": "설계", "it": "설계", "risk": "기획", "approval": "기획"}


def item_plan(category_id: str, area: str, text: str, check: str, limit: int = 2) -> dict:
    """체크리스트 한 줄의 처리 단계와 필요 산출물.
    {'phase': '설계', 'deliverables': [{'code': 'SEC-03', 'name': '암호화 적용 명세서', 'phase': '설계'}]}
    항목의 단계(언제 확인하나)와 서식의 작성 단계(언제 만드나)는 다를 수 있다."""
    phase, codes = None, []
    if category_id == "approval" and area in APPROVAL_PLAN:
        phase, codes = APPROVAL_PLAN[area]
    else:
        low = f"{area} {text} {check}".lower()
        for words, rule_phase, rule_codes in PLAN_RULES:
            if any(w in low for w in words):
                phase = phase or rule_phase
                codes += [c for c in rule_codes if c not in codes]
    return {
        "phase": phase or DEFAULT_PHASE.get(category_id, "설계"),
        "deliverables": [{"code": c, "name": FORMS[c][0], "phase": FORMS[c][1]} for c in codes[:limit]],
    }
